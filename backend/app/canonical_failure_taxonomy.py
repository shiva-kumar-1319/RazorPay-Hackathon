def get_canonical_failure(code: str) -> FailureDefinition:
    """Retrieve canonical definition for any failure code, handling casing and gateway mappings."""
    if not code:
        return CANONICAL_FAILURE_TAXONOMY["TIMEOUT"]
    normalized = code.strip().upper()
    if normalized in CANONICAL_FAILURE_TAXONOMY:
        return CANONICAL_FAILURE_TAXONOMY[normalized]
    mapped_code = GATEWAY_CODE_MAP.get(normalized)
    if mapped_code and mapped_code in CANONICAL_FAILURE_TAXONOMY:
        return CANONICAL_FAILURE_TAXONOMY[mapped_code]
    # Check if category prefix or common keyword matches
    if any(term in normalized for term in ("BLOCK", "STOLEN", "FRAUD", "LOST", "EXPIRED")):
        return CANONICAL_FAILURE_TAXONOMY["FRAUD_REJECTED" if "FRAUD" in normalized else "BLOCKED_CARD"]
    if any(term in normalized for term in ("OTP", "AUTH", "CANCEL", "3DS")):
        return CANONICAL_FAILURE_TAXONOMY["OTP_TIMEOUT" if "EXPIRE" in normalized or "TIMEOUT" in normalized else "3DS_FAILURE"]
    if any(term in normalized for term in ("TIMEOUT", "GATEWAY", "NETWORK", "DOWN", "SERVER")):
        return CANONICAL_FAILURE_TAXONOMY["TIMEOUT"]
    # Safe default: PAYMENT_METHOD CARD_DECLINED
    return CANONICAL_FAILURE_TAXONOMY["CARD_DECLINED"]


def is_recoverable(code: str) -> bool:
    """Return whether a failure code is legally and technically recoverable."""
    return get_canonical_failure(code).recoverable


def get_permitted_actions(code: str) -> tuple[str, ...]:
    """Return permitted action strings for a given failure code."""
    return get_canonical_failure(code).permitted_actions
