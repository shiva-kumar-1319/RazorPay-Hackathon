"""Canonical Failure Taxonomy — Single Source of Truth for Payment Failure Codes.

Defines the authoritative catalog of payment failure codes, classifications,
permitted recovery actions, retry bounds, delays, messages, and compliance notes.
All failure intelligence, policy, simulation, decision engine, and evaluation
subsystems import from this canonical module.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any


class CanonicalCategory(str, Enum):
    HARD_FAILURE = "HARD_FAILURE"
    PAYMENT_METHOD = "PAYMENT_METHOD"
    CUSTOMER_ACTION = "CUSTOMER_ACTION"
    TEMPORARY = "TEMPORARY"


@dataclass(frozen=True)
class FailureDefinition:
    code: str
    category: CanonicalCategory
    recoverable: bool
    permitted_actions: tuple[str, ...]
    suggested_action: str
    max_retries: int
    delay_seconds: int
    customer_message: str
    merchant_reason: str
    compliance_note: str
    description: str = ""
    typical_gateways: tuple[str, ...] = ()
    typical_methods: tuple[str, ...] = ()
    alternative_methods: tuple[str, ...] = ()
    default_error_message: str = ""


